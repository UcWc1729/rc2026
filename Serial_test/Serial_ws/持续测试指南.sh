  Q: 电机不转动？
  A: 1. 检查下位机是否正常运行
     2. 使用串口助手查看是否收到数据
     3. 检查电机驱动和使能信号
     4. 验证下位机协议解析是否正确

  Q: 串口权限错误？
  A: sudo chmod 666 /dev/ttyUSB0

  Q: 如何调整发送频率？
  A: 编辑continuous_send.py第93行:
     sender.send_rate = 100  # 改成你想要的频率

  Q: 如何紧急停止？
  A: 按 Ctrl+C 或在交互式界面按 0

